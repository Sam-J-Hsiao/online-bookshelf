export function deweyToCcl(dewey) {
  const n = parseFloat(String(dewey ?? "").replace(/\//g, "").match(/\d{1,3}(\.\d+)?/)?.[0]);
  if (!(n >= 0 && n < 1000)) return null;
  const hit = D2C.find(([a, b]) => n >= a && n < b);
  return hit ? { number: hit[2], main: Math.floor(+hit[2] / 100) * 100 } : null;
}
export const deweyMainToCclMain = m => (m == null ? null : D2C_MAIN[m] ?? null);

/** "177.2"、"873.57" → { number, main } */
export function parseCcl(raw) {
  if (raw == null || raw === "") return null;
  const m = String(raw).match(/^\s*(\d{3})(\.\d+)?\s*$/);
  if (!m) return null;
  return { number: m[1] + (m[2] || ""), main: Math.floor(+m[1] / 100) * 100 };
}

export const cclMainName = m => (m == null ? "未分類" : CCL.find(d => d.c === m)?.name || "");
export const ddcMainName = m => (m == null ? "未分類" : DEWEY.find(d => d.c === m)?.name || "");
/** 中文分類號的名稱：先找三位數專名，再找十位數類目，最後退回大類 */
export function cclName(number, main) {
  const n3 = String(number || "").slice(0, 3);
  return CCL_NUM[n3] || CCL_DIV[n3] || CCL_DIV[n3.slice(0, 2) + "0"] || cclMainName(main);
}

/** 書屬於哪一櫃：中文書 zh／英文書（含其他外文） en */
export const shelfOf = b => (b.lang === "zh" ? "zh" : "en");

/**
 * 一本書在它那一櫃的分類。
 * 回傳 { sys: "ccl"|"ddc", sysName, number, main, mainName, name, guessed, from }
 * from：推算時的來源說明（例如「由杜威 158 推算」）
 */
export function classOf(b) {
  if (shelfOf(b) === "zh") {
    let number = b.ccl || "", main = b.cclMain ?? null, guessed = !!b.cclGuessed, from = "";
    if (!number && main == null) {                                   // 舊資料或查詢只有杜威：即時推算
      const d = b.dewey ? deweyToCcl(b.dewey) : null;
      if (d) { number = d.number; main = d.main; guessed = true; from = `由杜威 ${b.dewey} 推算`; }
      else if (b.deweyMain != null) { main = deweyMainToCclMain(b.deweyMain); guessed = true; from = "由杜威大類推算"; }
    } else if (guessed && b.dewey) from = `由杜威 ${b.dewey} 推算`;
    return { sys: "ccl", sysName: "中文圖書分類", number, main, mainName: cclMainName(main),
      name: number ? cclName(number, main) : cclMainName(main), guessed, from };
  }
  const dd = parseDewey(b.dewey);
  const main = dd ? dd.main : b.deweyMain ?? null;
  return { sys: "ddc", sysName: "杜威分類", number: dd?.number || "", main, mainName: ddcMainName(main),
    name: ddcMainName(main), guessed: !dd && !!b.deweyGuessed, from: !dd && b.deweyGuessed ? "依主題推測" : "" };
}

/** 排序用：類號補齊位數，未分類排最後 */
export function classSortKey(b) {
  const c = classOf(b);
  if (c.main == null) return "999";
  return (c.number || pad3(c.main)).padEnd(12, "0");
}


const mixWhite = (hex, t) => "#" + [1, 3, 5].map(i => Math.round(parseInt(hex.slice(i, i + 2), 16) * (1 - t) + 255 * t).toString(16).padStart(2, "0")).join("");
/** 回傳 [深, 淺] 兩色（書封漸層用）；中文分類先換成同主題的杜威大類 */
export function subjectColors(b) {
  const c = classOf(b);
  const key = c.main == null ? null : c.sys === "ccl" ? C2D_MAIN[c.main] : c.main;
  const base = key == null ? NONE_COLOR : SUBJECT_COLOR[key];
  return [base, mixWhite(base, .16)];
}
